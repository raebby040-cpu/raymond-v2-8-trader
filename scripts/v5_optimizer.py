def split_walk_forward(
    df: pd.DataFrame,
) -> Dict[str, pd.DataFrame]:

    years = (
        df["timestamp"]
        .dt.year
    )

    return {
        "development": df[
            years == 2024
        ].copy(),

        "selection": df[
            years == 2025
        ].copy(),

        "holdout": df[
            years >= 2026
        ].copy(),

        "full": df.copy(),
    }



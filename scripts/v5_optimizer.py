# TRADE SIMULATOR
# ============================================================================

def simulate_candidate(
    df: pd.DataFrame,
    family: str,
    regime: str,
    min_signal_score: float,
    risk_reward: float,
    atr_stop_multiplier: float,
    risk_per_trade: float,
    max_trades_per_week: int,
    break_even_r: float,
    trailing_start_r: float,
    trailing_distance_r: float,
    starting_balance: float = 1000.0,
) -> Dict:

    balance = starting_balance
    peak_balance = balance

    trades = []

    weekly_counts: Dict[str, int] = {}

    position = None

    for i in range(60, len(df)):

        row = df.iloc[i]

        timestamp = row["timestamp"]

        week_key = (
            timestamp
            .strftime("%Y-%W")
        )

        signal, score = calculate_signal_score(
            row,
            family,
            regime,
        )

        # --------------------------------------------------------------
        # MANAGE OPEN POSITION
        # --------------------------------------------------------------

        if position is not None:

            direction = position["direction"]
            entry = position["entry"]
            stop = position["stop"]
            target = position["target"]
            risk = position["risk"]

            high = row["high"]
            low = row["low"]

            # Break-even
            if direction == "BUY":

                if high >= entry + risk * break_even_r:
                    position["stop"] = max(
                        position["stop"],
                        entry,
                    )

                if high >= (
                    entry +
                    risk * trailing_start_r
                ):
                    new_stop = (
                        high -
                        risk * trailing_distance_r
                    )

                    position["stop"] = max(
                        position["stop"],
                        new_stop,
                    )

                if low <= position["stop"]:

                    exit_price = position["stop"]

                    r_multiple = (
                        exit_price - entry
                    ) / risk

                    pnl = (
                        balance *
                        risk_per_trade *
                        r_multiple
                    )

                    balance += pnl

                    trades.append(
                        {
                            "timestamp": timestamp,
                            "family": family,
                            "regime": regime,
                            "direction": direction,
                            "entry": entry,
                            "exit": exit_price,
                            "r": r_multiple,
                            "pnl": pnl,
                            "reason": "SL_OR_TRAILING",
                        }
                    )

                    position = None

                elif high >= target:

                    exit_price = target

                    r_multiple = risk_reward

                    pnl = (
                        balance *
                        risk_per_trade *
                        r_multiple
                    )

                    balance += pnl

                    trades.append(
                        {
                            "timestamp": timestamp,
                            "family": family,
                            "regime": regime,
                            "direction": direction,
                            "entry": entry,
                            "exit": exit_price,
                            "r": r_multiple,
                            "pnl": pnl,
                            "reason": "TP",
                        }
                    )

                    position = None

            else:

                if low <= entry - risk * break_even_r:
                    position["stop"] = min(
                        position["stop"],
                        entry,
                    )

                if low <= (
                    entry -
                    risk * trailing_start_r
                ):
                    new_stop = (
                        low +
                        risk * trailing_distance_r
                    )

                    position["stop"] = min(
                        position["stop"],
                        new_stop,
                    )

                if high >= position["stop"]:

                    exit_price = position["stop"]

                    r_multiple = (
                        entry - exit_price
                    ) / risk

                    pnl = (
                        balance *
                        risk_per_trade *
                        r_multiple
                    )

                    balance += pnl

                    trades.append(
                        {
                            "timestamp": timestamp,
                            "family": family,
                            "regime": regime,
                            "direction": direction,
                            "entry": entry,
                            "exit": exit_price,
                            "r": r_multiple,
                            "pnl": pnl,
                            "reason": "SL_OR_TRAILING",
                        }
                    )

                    position = None

                elif low <= target:

                    exit_price = target

                    r_multiple = risk_reward

                    pnl = (
                        balance *
                        risk_per_trade *
                        r_multiple
                    )

                    balance += pnl

                    trades.append(
                        {
                            "timestamp": timestamp,
                            "family": family,
                            "regime": regime,
                            "direction": direction,
                            "entry": entry,
                            "exit": exit_price,
                            "r": r_multiple,
                            "pnl": pnl,
                            "reason": "TP",
                        }
                    )

                    position = None

        # --------------------------------------------------------------
        # OPEN NEW POSITION
        # --------------------------------------------------------------

        if position is None:

            count = weekly_counts.get(
                week_key,
                0,
            )

            if count >= max_trades_per_week:
                continue

            if score < min_signal_score:
                continue

            if signal not in {"BUY", "SELL"}:
                continue

            atr = row["atr14"]

            if pd.isna(atr) or atr <= 0:
                continue

            entry = row["close"]

            risk_distance = (
                atr *
                atr_stop_multiplier
            )

            if risk_distance <= 0:
                continue

            if signal == "BUY":

                stop = (
                    entry -
                    risk_distance
                )

                target = (
                    entry +
                    risk_distance *
                    risk_reward
                )

            else:

                stop = (
                    entry +
                    risk_distance
                )

                target = (
                    entry -
                    risk_distance *
                    risk_reward
                )

            position = {
                "direction": signal,
                "entry": entry,
                "stop": stop,
                "target": target,
                "risk": risk_distance,
            }

            weekly_counts[week_key] = (
                count + 1
            )

    # ------------------------------------------------------------------
    # METRICS
    # ------------------------------------------------------------------

    if not trades:

        return {
            "trades": 0,
            "wins": 0,
            "losses": 0,
            "gross_profit": 0.0,
            "gross_loss": 0.0,
            "net_profit": 0.0,
            "return_pct": 0.0,
            "max_drawdown_pct": 0.0,
            "profit_factor": 0.0,
            "expectancy_r": 0.0,
            "win_rate": 0.0,
            "positive_periods": 0,
            "negative_periods": 0,
            "consistency_pct": 0.0,
            "trade_records": [],
        }

    trade_df = pd.DataFrame(trades)

    wins = int(
        (trade_df["pnl"] > 0).sum()
    )

    losses = int(
        (trade_df["pnl"] < 0).sum()
    )

    gross_profit = float(
        trade_df.loc[
            trade_df["pnl"] > 0,
            "pnl",
        ].sum()
    )

    gross_loss = float(
        trade_df.loc[
            trade_df["pnl"] < 0,
            "pnl",
        ].sum()
    )

    net_profit = float(
        trade_df["pnl"].sum()
    )

    return_pct = (
        (balance - starting_balance) /
        starting_balance *
        100
    )

    equity = (
        starting_balance +
        trade_df["pnl"].cumsum()
    )

    running_peak = equity.cummax()

    drawdown = (
        running_peak - equity
    ) / running_peak * 100

    max_drawdown_pct = float(
        drawdown.max()
    )

    if gross_loss < 0:
        profit_factor = (
            gross_profit /
            abs(gross_loss)
        )
    else:
        profit_factor = 999.0

    expectancy_r = float(
        trade_df["r"].mean()
    )

    win_rate = (
        wins /
        len(trade_df) *
        100
    )

    # Monthly consistency
    trade_df["period"] = (
        pd.to_datetime(
            trade_df["timestamp"],
            utc=True,
        )
        .dt.to_period("M")
        .astype(str)
    )

    period_results = (
        trade_df
        .groupby("period")["pnl"]
        .sum()
    )

    positive_periods = int(
        (period_results > 0).sum()
    )

    negative_periods = int(
        (period_results < 0).sum()
    )

    total_periods = (
        positive_periods +
        negative_periods
    )

    consistency_pct = (
        positive_periods /
        total_periods *
        100
        if total_periods
        else 0.0
    )

    return {
        "trades": len(trade_df),
        "wins": wins,
        "losses": losses,
        "gross_profit": gross_profit,
        "gross_loss": gross_loss,
        "net_profit": net_profit,
        "return_pct": return_pct,
        "max_drawdown_pct": max_drawdown_pct,
        "profit_factor": profit_factor,
        "expectancy_r": expectancy_r,
        "win_rate": win_rate,
        "positive_periods": positive_periods,
        "negative_periods": negative_periods,
        "consistency_pct": consistency_pct,
        "trade_records": trades,
    }



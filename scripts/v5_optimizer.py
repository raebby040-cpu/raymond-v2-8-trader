def build_grid() -> List[Dict]:

    grid = {
        "strategy_family": STRATEGY_FAMILIES,

        "regime": REGIMES,

        "min_signal_score": [
            55,
            60,
            65,
            70,
            75,
        ],

        "risk_reward": [
            1.5,
            2.0,
            2.5,
            3.0,
            3.5,
            4.0,
        ],

        "atr_stop_multiplier": [
            0.8,
            1.0,
            1.2,
            1.4,
            1.6,
        ],

        "risk_per_trade": [
            0.01,
            0.015,
            0.02,
            0.025,
        ],

        "max_trades_per_week": [
            3,
            5,
            8,
        ],

        "break_even_r": [
            0.8,
            1.0,
        ],

        "trailing_start_r": [
            1.5,
            2.0,
            2.5,
        ],

        "trailing_distance_r": [
            0.75,
            1.0,
            1.25,
        ],
    }

    keys = list(grid.keys())

    combinations = []

    for values in itertools.product(
        *[
            grid[key]
            for key in keys
        ]
    ):
        combinations.append(
            dict(
                zip(keys, values)
            )
        )

    return combinations



"""
RAYMOND V2.8 - V5 OPTIMIZER
============================

STEP 2 OF V5 RESEARCH ARCHITECTURE

Purpose
-------
Research-only optimizer for the V5 multi-strategy engine.

This optimizer is deliberately separated from V4.

It evaluates strategy families and parameter combinations using:
    - compounded return
    - profit factor
    - expectancy
    - maximum drawdown
    - consistency
    - trade count
    - yearly performance
    - walk-forward stability

IMPORTANT
---------
This file does NOT:
    - connect to MT5
    - connect to Exness
    - place broker orders
    - modify broker positions
    - enable live trading

The optimizer is a research component only.

Design principle
----------------
Do NOT optimize purely for win rate.

A strategy with:
    70% win rate + tiny winners + huge losses

can be much worse than:

    48% win rate + large winners + controlled losses.

V5 therefore uses a multi-objective score and keeps a Pareto-style
candidate set instead of blindly selecting the highest return.
"""


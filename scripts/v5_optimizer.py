def detect_regime(row: pd.Series) -> str:
    ema20 = row["ema20"]
    ema50 = row["ema50"]
    atr_ratio = row["atr_ratio"]
    close = row["close"]

    if any(
        pd.isna(x)
        for x in [
            ema20,
            ema50,
            atr_ratio,
            close,
        ]
    ):
        return "TRANSITION"

    distance = abs(ema20 - ema50) / max(
        abs(close),
        1e-9,
    )

    if atr_ratio < 0.70:
        return "VOLATILITY_COMPRESSION"

    if atr_ratio > 1.50:
        return "VOLATILITY_EXPANSION"

    if (
        ema20 > ema50
        and close > ema50
        and distance > 0.001
    ):
        return "BULL_TREND"

    if (
        ema20 < ema50
        and close < ema50
        and distance > 0.001
    ):
        return "BEAR_TREND"

    if distance < 0.001:
        return "RANGE"

    return "TRANSITION"



# OPTIMIZATION OBJECTIVE
# ============================================================================

def optimization_score(metrics: Dict) -> float:

    trades = metrics["trades"]

    if trades < 20:
        return -10000.0

    pf = min(
        metrics["profit_factor"],
        5.0,
    )

    ret = metrics["return_pct"]

    dd = metrics["max_drawdown_pct"]

    expectancy = metrics["expectancy_r"]

    consistency = (
        metrics["consistency_pct"]
    )

    # Growth reward
    growth_component = (
        np.sign(ret) *
        math.log1p(abs(ret)) *
        12.0
    )

    # Profit factor reward
    pf_component = (
        max(pf - 1.0, -1.0) *
        25.0
    )

    # Expectancy
    expectancy_component = (
        np.clip(
            expectancy,
            -2.0,
            2.0,
        ) *
        20.0
    )

    # Consistency
    consistency_component = (
        consistency *
        0.30
    )

    # Drawdown penalty
    drawdown_penalty = (
        max(dd - 10.0, 0.0) *
        2.5
    )

    # Penalize very small samples.
    sample_bonus = min(
        math.log1p(trades) * 2.0,
        15.0,
    )

    score = (
        growth_component
        + pf_component
        + expectancy_component
        + consistency_component
        + sample_bonus
        - drawdown_penalty
    )

    return float(score)



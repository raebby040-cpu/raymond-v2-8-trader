def calculate_signal_score(
    row: pd.Series,
    family: str,
    regime: str,
) -> Tuple[str, float]:
    """
    Produce a normalized V5 research signal.

    BUY = +score
    SELL = -score
    WAIT = 0
    """

    if regime != detect_regime(row):
        return "WAIT", 0.0

    close = row["close"]
    ema20 = row["ema20"]
    ema50 = row["ema50"]
    rsi = row["rsi14"]
    macd = row["macd"]
    macd_signal = row["macd_signal"]

    if any(
        pd.isna(x)
        for x in [
            close,
            ema20,
            ema50,
            rsi,
            macd,
            macd_signal,
        ]
    ):
        return "WAIT", 0.0

    buy = 0.0
    sell = 0.0

    # ------------------------------------------------------------------
    # TREND CONTINUATION
    # ------------------------------------------------------------------

    if family == "TREND_CONTINUATION":

        if regime == "BULL_TREND":
            buy += 30

            if close > ema20:
                buy += 20

            if macd > macd_signal:
                buy += 20

            if 52 <= rsi <= 72:
                buy += 20

            return "BUY", min(buy, 100)

        if regime == "BEAR_TREND":
            sell += 30

            if close < ema20:
                sell += 20

            if macd < macd_signal:
                sell += 20

            if 28 <= rsi <= 48:
                sell += 20

            return "SELL", min(sell, 100)

    # ------------------------------------------------------------------
    # PULLBACK / RETEST
    # ------------------------------------------------------------------

    if family == "PULLBACK_RETEST":

        if regime == "BULL_TREND":

            if close >= ema20:
                buy += 25

            if close > ema50:
                buy += 25

            if macd >= macd_signal:
                buy += 20

            if 45 <= rsi <= 65:
                buy += 20

            return "BUY", min(buy, 100)

        if regime == "BEAR_TREND":

            if close <= ema20:
                sell += 25

            if close < ema50:
                sell += 25

            if macd <= macd_signal:
                sell += 20

            if 35 <= rsi <= 55:
                sell += 20

            return "SELL", min(sell, 100)

    # ------------------------------------------------------------------
    # BREAKOUT
    # ------------------------------------------------------------------

    if family == "BREAKOUT":

        range_high = row.get("range_high")
        range_low = row.get("range_low")

        if pd.notna(range_high) and close > range_high:
            buy += 50

            if macd > macd_signal:
                buy += 20

            if rsi > 55:
                buy += 20

            return "BUY", min(buy, 100)

        if pd.notna(range_low) and close < range_low:
            sell += 50

            if macd < macd_signal:
                sell += 20

            if rsi < 45:
                sell += 20

            return "SELL", min(sell, 100)

    # ------------------------------------------------------------------
    # LIQUIDITY REVERSAL
    # ------------------------------------------------------------------

    if family == "LIQUIDITY_REVERSAL":

        previous_low = row.get("range_low")
        previous_high = row.get("range_high")

        if pd.notna(previous_low):

            if (
                row["low"] < previous_low
                and close > previous_low
            ):
                buy += 55

                if rsi < 45:
                    buy += 20

                if macd > macd_signal:
                    buy += 15

                return "BUY", min(buy, 100)

        if pd.notna(previous_high):

            if (
                row["high"] > previous_high
                and close < previous_high
            ):
                sell += 55

                if rsi > 55:
                    sell += 20

                if macd < macd_signal:
                    sell += 15

                return "SELL", min(sell, 100)

    # ------------------------------------------------------------------
    # RANGE MEAN REVERSION
    # ------------------------------------------------------------------

    if family == "RANGE_MEAN_REVERSION":

        if regime != "RANGE":
            return "WAIT", 0.0

        range_high = row.get("range_high")
        range_low = row.get("range_low")

        if (
            pd.notna(range_low)
            and close <= range_low * 1.001
            and rsi < 40
        ):
            buy = 70

            if macd > macd_signal:
                buy += 20

            return "BUY", min(buy, 100)

        if (
            pd.notna(range_high)
            and close >= range_high * 0.999
            and rsi > 60
        ):
            sell = 70

            if macd < macd_signal:
                sell += 20

            return "SELL", min(sell, 100)

    # ------------------------------------------------------------------
    # MOMENTUM EXPANSION
    # ------------------------------------------------------------------

    if family == "MOMENTUM_EXPANSION":

        if regime != "VOLATILITY_EXPANSION":
            return "WAIT", 0.0

        if (
            close > ema20
            and ema20 > ema50
            and macd > macd_signal
            and rsi > 55
        ):
            return "BUY", 90.0

        if (
            close < ema20
            and ema20 < ema50
            and macd < macd_signal
            and rsi < 45
        ):
            return "SELL", 90.0

    return "WAIT", 0.0


